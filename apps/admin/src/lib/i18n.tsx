const dictionaries = { en, tr };
export type Locale = keyof typeof dictionaries;
export type T = (key: Key, vars?: Record<string, string | number>) => string;

const I18n = createContext<{ locale: Locale; t: T; setLocale: (l: Locale) => void } | null>(null);

function initialLocale(): Locale {
  try {
    const saved = localStorage.getItem('litho.locale');
    if (saved === 'tr' || saved === 'en') return saved;
  } catch {
    // storage blocked; fall through
  }
  return navigator.languages.some((l) => l.toLowerCase().startsWith('tr')) ? 'tr' : 'en';
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>(initialLocale);
  const value = useMemo(() => {
    const dict = dictionaries[locale];
    const t: T = (key, vars) =>
      dict[key].replace(/\{(\w+)\}/g, (_, name: string) => String(vars?.[name] ?? ''));
    const setLocale = (l: Locale) => {
      setLocaleState(l);
      document.documentElement.lang = l;
      try {
        localStorage.setItem('litho.locale', l);
      } catch {
        // ignore
      }
    };
    return { locale, t, setLocale };
  }, [locale]);
  return <I18n.Provider value={value}>{children}</I18n.Provider>;
}

/** Resolves a schema label (a string or one per locale) in the admin's language. */
export function useLabel() {
  const { locale } = useI18n();
  return (value: string | Record<string, string> | undefined, fallback = '') =>
    label(value, locale) || fallback;
}

export function useI18n() {
  const ctx = useContext(I18n);
  if (!ctx) throw new Error('useI18n outside I18nProvider');
  return ctx;
}

/** Dates in the admin's language, never a hardcoded format. */
export function useFormat() {
  const { locale } = useI18n();
  return useMemo(() => {
    const date = new Intl.DateTimeFormat(locale, { dateStyle: 'medium' });
    const dateTime = new Intl.DateTimeFormat(locale, { dateStyle: 'medium', timeStyle: 'short' });
    const bytes = new Intl.NumberFormat(locale, {
      style: 'unit',
      unit: 'kilobyte',
      maximumFractionDigits: 0,
    });
    return {
      date: (iso: string) => date.format(new Date(iso)),
      dateTime: (iso: string) => dateTime.format(new Date(iso)),
      kb: (n: number) => bytes.format(Math.max(1, Math.round(n / 1024))),
    };
  }, [locale]);
}
